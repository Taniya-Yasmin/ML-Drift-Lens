DO $$
DECLARE
  predictions_relation regclass := to_regclass('public.predictions');
  relation_kind "char";
  expected_column record;
  actual_data_type text;
  actual_length integer;
  actual_not_null boolean;
  actual_default text;
  id_attnum smallint;
BEGIN
  IF predictions_relation IS NULL THEN
    CREATE TABLE public.predictions (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      model_id varchar(255) NOT NULL,
      model_version varchar(50) NOT NULL,
      preprocessing_version varchar(50) NOT NULL,
      input_features jsonb NOT NULL,
      prediction varchar(50) NOT NULL,
      prediction_class integer NOT NULL,
      confidence double precision NOT NULL,
      request_id varchar(255) NOT NULL,
      timestamp timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      actual_label varchar(50),
      created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT predictions_request_id_key UNIQUE (request_id),
      CONSTRAINT predictions_prediction_check CHECK (prediction IN ('normal', 'attack')),
      CONSTRAINT predictions_prediction_class_check CHECK (prediction_class IN (0, 1)),
      CONSTRAINT predictions_confidence_check CHECK (confidence >= 0 AND confidence <= 1)
    );

    predictions_relation := 'public.predictions'::regclass;
  ELSE
    SELECT c.relkind
    INTO relation_kind
    FROM pg_class AS c
    WHERE c.oid = predictions_relation;

    IF relation_kind NOT IN ('r', 'p') THEN
      RAISE EXCEPTION
        'Incompatible predictions relation: public.predictions is not a table';
    END IF;

    SELECT a.attnum
    INTO id_attnum
    FROM pg_attribute AS a
    WHERE a.attrelid = predictions_relation
      AND a.attname = 'id'
      AND NOT a.attisdropped;

    IF id_attnum IS NULL THEN
      RAISE EXCEPTION 'Incompatible predictions table: missing column "id"';
    END IF;

    IF NOT EXISTS (
      SELECT 1
      FROM pg_constraint AS c
      WHERE c.conrelid = predictions_relation
        AND c.contype = 'p'
        AND c.conkey = ARRAY[id_attnum]::smallint[]
    ) THEN
      RAISE EXCEPTION
        'Incompatible predictions table: primary key must apply only to id';
    END IF;

    IF NOT EXISTS (
      SELECT 1
      FROM pg_attribute AS a
      WHERE a.attrelid = predictions_relation
        AND a.attnum = id_attnum
        AND a.attidentity = 'd'
    ) THEN
      RAISE EXCEPTION
        'Incompatible predictions table: id must use GENERATED BY DEFAULT AS IDENTITY';
    END IF;

    FOR expected_column IN
      SELECT *
      FROM (VALUES
        ('id', 'integer', NULL::integer, true, false),
        ('model_id', 'character varying', 255, true, false),
        ('model_version', 'character varying', 50, true, false),
        ('preprocessing_version', 'character varying', 50, true, false),
        ('input_features', 'jsonb', NULL::integer, true, false),
        ('prediction', 'character varying', 50, true, false),
        ('prediction_class', 'integer', NULL::integer, true, false),
        ('confidence', 'double precision', NULL::integer, true, false),
        ('request_id', 'character varying', 255, true, false),
        ('timestamp', 'timestamp with time zone', NULL::integer, true, true),
        ('actual_label', 'character varying', 50, false, false),
        ('created_at', 'timestamp with time zone', NULL::integer, true, true),
        ('updated_at', 'timestamp with time zone', NULL::integer, true, true)
      ) AS expected(
        column_name,
        expected_data_type,
        expected_length,
        required_not_null,
        requires_current_timestamp_default
      )
    LOOP
      SELECT
        c.data_type,
        c.character_maximum_length,
        c.is_nullable = 'NO',
        pg_get_expr(d.adbin, d.adrelid)
      INTO actual_data_type, actual_length, actual_not_null, actual_default
      FROM information_schema.columns AS c
      JOIN pg_class AS table_row
        ON table_row.relname = c.table_name
       AND table_row.relnamespace = 'public'::regnamespace
      JOIN pg_attribute AS attribute_row
        ON attribute_row.attrelid = table_row.oid
       AND attribute_row.attname = c.column_name
       AND NOT attribute_row.attisdropped
      LEFT JOIN pg_attrdef AS d
        ON d.adrelid = attribute_row.attrelid
       AND d.adnum = attribute_row.attnum
      WHERE c.table_schema = 'public'
        AND c.table_name = 'predictions'
        AND c.column_name = expected_column.column_name;

      IF actual_data_type IS NULL THEN
        RAISE EXCEPTION
          'Incompatible predictions table: missing column "%"',
          expected_column.column_name;
      END IF;

      IF actual_data_type <> expected_column.expected_data_type THEN
        RAISE EXCEPTION
          'Incompatible predictions table: column "%" has type "%", expected "%"',
          expected_column.column_name,
          actual_data_type,
          expected_column.expected_data_type;
      END IF;

      IF expected_column.expected_length IS NOT NULL
         AND actual_length IS DISTINCT FROM expected_column.expected_length THEN
        RAISE EXCEPTION
          'Incompatible predictions table: column "%" has length "%", expected "%"',
          expected_column.column_name,
          COALESCE(actual_length::text, 'unbounded'),
          expected_column.expected_length;
      END IF;

      IF expected_column.required_not_null AND NOT actual_not_null THEN
        RAISE EXCEPTION
          'Incompatible predictions table: column "%" must be NOT NULL',
          expected_column.column_name;
      END IF;

      IF expected_column.requires_current_timestamp_default
         AND lower(
           regexp_replace(
             regexp_replace(COALESCE(actual_default, ''), '\s+', '', 'g'),
             '[()]', '', 'g'
           )
         ) NOT IN (
           'current_timestamp',
           'current_timestamp::timestampwithtimezone',
           'now'
         ) THEN
        RAISE EXCEPTION
          'Incompatible predictions table: column "%" must default to CURRENT_TIMESTAMP',
          expected_column.column_name;
      END IF;
    END LOOP;
  END IF;
END
$$;

DO $$
DECLARE
  predictions_relation regclass := 'public.predictions'::regclass;
  request_id_attnum smallint;
  constraint_row record;
  normalized_definition text;
BEGIN
  SELECT a.attnum
  INTO request_id_attnum
  FROM pg_attribute AS a
  WHERE a.attrelid = predictions_relation
    AND a.attname = 'request_id'
    AND NOT a.attisdropped;

  SELECT *
  INTO constraint_row
  FROM pg_constraint
  WHERE conrelid = predictions_relation
    AND conname = 'predictions_request_id_key';

  IF FOUND THEN
    IF constraint_row.contype <> 'u'
       OR constraint_row.conkey <> ARRAY[request_id_attnum]::smallint[] THEN
      RAISE EXCEPTION
        'Incompatible predictions table: predictions_request_id_key is not UNIQUE(request_id)';
    END IF;
  ELSE
    ALTER TABLE public.predictions
      ADD CONSTRAINT predictions_request_id_key UNIQUE (request_id);
  END IF;

  SELECT *
  INTO constraint_row
  FROM pg_constraint
  WHERE conrelid = predictions_relation
    AND conname = 'predictions_prediction_check';

  IF FOUND THEN
    normalized_definition := lower(
      regexp_replace(pg_get_constraintdef(constraint_row.oid, true), '\s+', '', 'g')
    );
    IF constraint_row.contype <> 'c'
      OR normalized_definition !~ '^check\(\(*prediction\)*(:{2}[a-z_]+)?=any\(\(*array\[''normal''(:{2}[a-z_]+)?,''attack''(:{2}[a-z_]+)?\]\)*(:{2}[a-z_]+\[\])?\)*$' THEN
      RAISE EXCEPTION
        'Incompatible predictions table: predictions_prediction_check has an incompatible definition';
    END IF;
  ELSE
    ALTER TABLE public.predictions
      ADD CONSTRAINT predictions_prediction_check
      CHECK (prediction IN ('normal', 'attack'));
  END IF;

  SELECT *
  INTO constraint_row
  FROM pg_constraint
  WHERE conrelid = predictions_relation
    AND conname = 'predictions_prediction_class_check';

  IF FOUND THEN
    normalized_definition := lower(
      regexp_replace(pg_get_constraintdef(constraint_row.oid, true), '\s+', '', 'g')
    );
    IF constraint_row.contype <> 'c'
      OR normalized_definition !~ '^check\(\(*prediction_class\)*(:{2}[a-z_]+)?=any\(\(*array\[0,1\]\)*(:{2}[a-z_]+\[\])?\)*$' THEN
      RAISE EXCEPTION
        'Incompatible predictions table: predictions_prediction_class_check has an incompatible definition';
    END IF;
  ELSE
    ALTER TABLE public.predictions
      ADD CONSTRAINT predictions_prediction_class_check
      CHECK (prediction_class IN (0, 1));
  END IF;

  SELECT *
  INTO constraint_row
  FROM pg_constraint
  WHERE conrelid = predictions_relation
    AND conname = 'predictions_confidence_check';

  IF FOUND THEN
    normalized_definition := lower(
      regexp_replace(pg_get_constraintdef(constraint_row.oid, true), '\s+', '', 'g')
    );
    IF constraint_row.contype <> 'c'
      OR normalized_definition !~ '^check\(\(*confidence\)*>=\(*0\)*(:{2}[a-z_]+)?\)*and\(*confidence\)*<=\(*1\)*(:{2}[a-z_]+)?\)*$' THEN
      RAISE EXCEPTION
        'Incompatible predictions table: predictions_confidence_check has an incompatible definition';
    END IF;
  ELSE
    ALTER TABLE public.predictions
      ADD CONSTRAINT predictions_confidence_check
      CHECK (confidence >= 0 AND confidence <= 1);
  END IF;
END
$$;

DO $$
DECLARE
  predictions_relation regclass := 'public.predictions'::regclass;
  expected_index record;
  index_row record;
  expected_attnum smallint;
BEGIN
  FOR expected_index IN
    SELECT *
    FROM (VALUES
      ('idx_predictions_model_id', 'model_id', false),
      ('idx_predictions_timestamp', 'timestamp', true)
    ) AS expected(index_name, column_name, descending)
  LOOP
    SELECT a.attnum
    INTO expected_attnum
    FROM pg_attribute AS a
    WHERE a.attrelid = predictions_relation
      AND a.attname = expected_index.column_name
      AND NOT a.attisdropped;

    SELECT
      i.indisvalid AS is_valid,
      i.indnkeyatts AS key_count,
      i.indkey[0] AS first_attnum,
      COALESCE((i.indoption[0] & 1) = 1, false) AS is_descending,
      i.indpred IS NULL AS is_not_partial,
      i.indexprs IS NULL AS is_not_expression
    INTO index_row
    FROM pg_class AS index_class
    JOIN pg_index AS i ON i.indexrelid = index_class.oid
    WHERE index_class.relnamespace = 'public'::regnamespace
      AND index_class.relname = expected_index.index_name
      AND i.indrelid = predictions_relation;

    IF FOUND THEN
      IF NOT index_row.is_valid
         OR index_row.key_count <> 1
         OR index_row.first_attnum <> expected_attnum
         OR index_row.is_descending <> expected_index.descending
         OR NOT index_row.is_not_partial
         OR NOT index_row.is_not_expression THEN
        RAISE EXCEPTION
          'Incompatible predictions table: index % has an incompatible definition',
          expected_index.index_name;
      END IF;
    ELSE
      IF expected_index.descending THEN
        EXECUTE format(
          'CREATE INDEX %I ON public.predictions (%I DESC)',
          expected_index.index_name,
          expected_index.column_name
        );
      ELSE
        EXECUTE format(
          'CREATE INDEX %I ON public.predictions (%I)',
          expected_index.index_name,
          expected_index.column_name
        );
      END IF;
    END IF;
  END LOOP;
END
$$;

